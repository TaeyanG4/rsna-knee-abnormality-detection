from tools.remote_bundle_v3 import read, sha256, protocol_files, FORBIDDEN_PREFIXES, WORKSPACE_TOML, DOCKER_IMAGE, CORPUS_DATASET  # noqa: E402,F401

PACKAGE = ROOT / 'kaggle' / 'packages' / 'KNEE_RUNNERS_V3B'
DATASET = 'knee-runners-v3b'
REMOTE_ENTRY = 'tools/remote_run_v3b.py'
