"""Remote GPU bundle v3b (Kaggle T4): the v3 bundle plus the EXP101 ResNet34 seed-43 job; one kernel trains all five folds with seed 43.

  python tools/remote_bundle_v3b.py build                  # -> kaggle/packages/KNEE_RUNNERS_V3B (private dataset <user>/knee-runners-v3b)
  python tools/remote_bundle_v3b.py publish [--wait 1200]  # create/version the private dataset (absolute path, D-B-015) and wait until listed
  python tools/remote_bundle_v3b.py wait [--wait 1200]     # only poll until every bundle file is listed
  python tools/remote_bundle_v3b.py kernel --job exp101:rn34-s43-5fold [--push]   # private T4 script kernel, image pinned, internet on

Same rules as tools/remote_bundle_v3.py (code, the seed-43 protocol directory, every file it binds by sha256 - which includes the seed-42
manifest and keys file, the EXP084 base split, the EXP099 fold files and Dread registration - and the Dread label CSV; no report text, no Gold,
no DICOM; every bound file verified against the manifest hashes). Differences: a separate dataset (knee-runners-v3b) so the running seed-42
kernel's dataset is never versioned, the remote entry tools/remote_run_v3b.py, and `kernels push` WITHOUT --timeout (D-B-015 item 13: a push
with --timeout now ends ERROR with an empty log). The 11 h session guard stays in the kernel script (--budget-hours 11.0).
"""
