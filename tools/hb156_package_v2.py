def proof(inventory, before, after):
    changed, unchanged, omitted, diff = [], [], [], []
    allowed = {'run.sh','tools/hb156_vast_v1.py',f'{OLD_STAGE}/manifest.json',f'{OLD_STAGE}/label-provenance.json'}
    for entry in inventory['files']:
        rel=entry['path']; dest=PACKAGE/rel.replace(OLD_STAGE,STAGE_NAME)
        if rel.startswith('evidence/') or rel in {'BUILD.md','LAUNCH.md',f'{OLD_STAGE}/cpu-validation.json',f'{OLD_STAGE}/soft-labels.csv'}:
            omitted.append(rel); continue
        old_sha=sha(PARENT/rel); new_sha=sha(dest)
        if old_sha==new_sha:
            unchanged.append(dict(path=rel,sha256=old_sha));continue
        need(rel in allowed,'non-allowlisted file changed: '+rel)
        changed.append(dict(path=rel,parent_sha256=old_sha,candidate_sha256=new_sha))
        if rel in ('run.sh','tools/hb156_vast_v1.py'):
            diff.extend(difflib.unified_diff((PARENT/rel).read_text(encoding='utf-8').splitlines(True),
                dest.read_text(encoding='utf-8').splitlines(True),fromfile='parent/'+rel,tofile='candidate/'+rel))
    deltas = sorted(k for k in after if before.get(k)!=after[k])
    need(set(deltas)=={'schema','version','run_dirs','source_bindings','content_sha256','train_labels',
        'label_sha256','label_provenance','label_provenance_sha256','label_file_name'},'unexpected manifest delta')
    expected=copy.deepcopy(before)
    for key in deltas: expected[key]=after[key]
    need(expected==after,'removed manifest field')
    write_json(WORK/'mechanical-diff.json',dict(status='PASS',parent_inventory_sha256=sha(PARENT/'INVENTORY.json'),
        parent_files_verified=len(inventory['files']),unchanged=unchanged,changed=changed,omitted=omitted,
        manifest_delta=deltas,recipe_byte_semantics_identical=True,trainer_byte_identical=True,
        roster_identical=True,pos_weight_identical=True,label_sha256=LABEL_SHA,
        label_note='Exact EXP143v2 fractional L2 CSV, not thresholded binary labels',
        redaction='Label rows and manifest target arrays intentionally not emitted; hashes and exact in-memory comparisons cover them'))
    write(WORK/'full-code.diff',''.join(diff))
    # New executable support code has no parent counterpart; include it in full.
    with (WORK/'full-code.diff').open('a',encoding='utf-8',newline='\n') as stream:
        for rel in ('tools/hb156_package_v2.py','tools/hb156_transfer_v2.ps1'):
            stream.writelines(difflib.unified_diff([], (ROOT/rel).read_text(encoding='utf-8').splitlines(True),
                fromfile='/dev/null',tofile=rel))


def archive():
    safe_build_target()
    excluded={'cpu-checkpoint.pt','INVENTORY.json','SHA256SUMS'}
    paths=sorted(p for p in PACKAGE.rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.name not in excluded)
    need(not any('cache' in p.relative_to(PACKAGE).parts for p in paths),'corpus must never be uploaded')
    inventory=[dict(path=p.relative_to(PACKAGE).as_posix(),bytes=p.stat().st_size,sha256=sha(p)) for p in paths]
    write_json(PACKAGE/'INVENTORY.json',dict(version=VERSION,files=inventory))
    write(PACKAGE/'SHA256SUMS',''.join(f"{p['sha256']}  {p['path']}\n" for p in inventory))
    target=WORK/(DEPLOY+'.tar')
    with tarfile.open(target,'w') as tar:
        for path in paths+[PACKAGE/'INVENTORY.json',PACKAGE/'SHA256SUMS']:
            tar.add(path,arcname=DEPLOY+'/'+path.relative_to(PACKAGE).as_posix(),recursive=False)
    write(target.with_suffix('.tar.sha256'),sha(target)+'  '+target.name+'\n')
    print(json.dumps(dict(status='ARCHIVED',files=len(paths),bytes=target.stat().st_size,sha256=sha(target))))


