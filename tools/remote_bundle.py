"""Package, launch and collect remote GPU runs (Colab, Kaggle notebooks, rented boxes).

Private Kaggle datasets carry everything a remote session needs:
  * <user>/knee-raptor-tools       (small, versioned often): training scripts, labels, folds,
    study metadata, reduced train.csv (UID + 12 labels, no report text), workspace skeleton.
  * <user>/knee-raptor-corpus-336  (32 GB, versioned rarely): the corpus shards + manifest.
  * <user>/knee-raptor-res-<tag>   one private dataset per Colab run (written by run_remote.py).
Kaggle notebook runs keep results in the notebook output instead (no token inside the notebook).
Everything stays private; nothing here submits to the competition or publishes publicly.

  python tools/remote_bundle.py build --kind tools|corpus      # writes kaggle/packages/KNEE_RAPTOR_TOOLS | _CORPUS_336
  python tools/remote_bundle.py publish --kind tools           # create (first time) or version the private dataset
  python tools/remote_bundle.py kernel --tag T --train "..." [--push]   # private Kaggle GPU notebook for one run
  python tools/remote_bundle.py fetch-kernel --tag T           # notebook output -> artifacts/experiments/T
  python tools/remote_bundle.py fetch-results [--tag T]        # Colab per-run datasets -> artifacts/experiments
"""
