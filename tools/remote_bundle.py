def slugify(prefix: str, tag: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", tag.lower()).strip("-")
    return (prefix + slug)[:50].rstrip("-")


def results_slug(tag: str) -> str:
    """Per-run results dataset slug; must match tools/colab/run_remote.py (a test checks it)."""
    return slugify(RESULTS_PREFIX, tag)


def kernel_slug(tag: str) -> str:
    return slugify(KERNEL_PREFIX, tag)


def username():
    out = subprocess.run([kaggle_exe(), "config", "view"], capture_output=True, text=True, encoding="utf-8")
    for line in out.stdout.splitlines():
        if line.strip().startswith("- username:"):
            return line.split(":", 1)[1].strip()
    raise SystemExit("kaggle username unknown; run `kaggle config view`")


def kaggle_exe():
    venv = ROOT / ".venv" / "Scripts" / "kaggle.exe"
    return str(venv) if venv.exists() else "kaggle"


def kaggle(*args, check=False):
    env = {**os.environ, "PYTHONIOENCODING": "utf-8"}
    r = subprocess.run([kaggle_exe(), *args], capture_output=True, text=True, encoding="utf-8", errors="replace", env=env)
    if check and r.returncode:
        raise SystemExit(f"kaggle {' '.join(args[:3])} failed: {(r.stderr or r.stdout)[-600:]}")
    return r


def link_or_copy(src: Path, dst: Path):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def mix_label_files():
    """label_mix.py outputs (UID + 12 label columns) and their recipe JSON. A CSV with any other
    column (for example report text) is refused so nothing beyond labels leaves this PC."""
    import pandas as pd
    allowed = {UID, *LAB, *(c + "_soft" for c in LAB)}
    files = []
    for csv_path in sorted((ROOT / MIX_DIR).glob("*.csv")):
        extra = set(pd.read_csv(csv_path, nrows=1).columns) - allowed
        if extra:
            raise SystemExit(f"{csv_path.name}: unexpected columns {sorted(extra)}; only UID + labels may be uploaded")
        files.append(csv_path)
        if csv_path.with_suffix(".json").exists():
            files.append(csv_path.with_suffix(".json"))
    return files


def build_tools(out: Path, user: str):
    if out.exists():
        shutil.rmtree(out)
    (out / "training" / "src").mkdir(parents=True)
    for name in SCRIPTS:
        shutil.copy2(ROOT / "training" / "src" / name, out / "training" / "src" / name)
    shutil.copy2(ROOT / "tools" / "colab" / "run_remote.py", out / "run_remote.py")
    (out / "config").mkdir(); (out / "config" / "workspace.toml").write_text(
        'schema_version = 1\nlayout_version = 2\ncompetition = "rsna-knee-abnormality-detection"\n[paths]\ncache = "storage/cache/derived"\n'
        'experiments = "artifacts/experiments"\n', encoding="utf-8")
    import pandas as pd
    tr = pd.read_csv(COMP / "train.csv", dtype={UID: str})
    (out / "storage" / "competition").mkdir(parents=True)
    tr[[UID] + LAB].to_csv(out / "storage" / "competition" / "train.csv", index=False)  # labels only; report text stays local
    pd.read_csv(COMP / "test.csv", dtype={UID: str})[[UID]].to_csv(out / "storage" / "competition" / "test.csv", index=False)
    for rel in LABEL_FILES:
        src = ROOT / rel
        if src.exists():
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, out / rel)
    for src in mix_label_files():  # R2 label-mix outputs, so remote folds can train on them
        rel = src.relative_to(ROOT)
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, out / rel)
    folds = EXPERIMENTS / "EXP026_GROUPED_FROZEN_PROBE" / "folds.csv"
    (out / "artifacts" / "experiments" / "EXP026_GROUPED_FROZEN_PROBE").mkdir(parents=True)
    shutil.copy2(folds, out / "artifacts" / "experiments" / "EXP026_GROUPED_FROZEN_PROBE" / "folds.csv")
    (out / "requirements-remote.txt").write_text("timm>=1.0.19\nscikit-learn\npandas\nnumpy\n", encoding="utf-8")
    (out / "README.md").write_text("Private training bundle for RSNA Knee (KneeOps). See run_remote.py.\n", encoding="utf-8")
    meta = {"title": "knee-raptor-tools", "id": f"{user}/knee-raptor-tools", "licenses": [{"name": "other"}],
            "isPrivate": True, "description": "Private: training scripts, labels, folds for the RSNA Knee Raptor pipeline."}
    (out / "dataset-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    manifest = {"built_at": time.strftime("%Y-%m-%dT%H:%M:%S"), "files": sorted(str(p.relative_to(out)).replace(os.sep, "/") for p in out.rglob("*") if p.is_file())}
    (out / "bundle_manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    return manifest


def build_corpus(out: Path, user: str):
    out.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((CORPUS / "manifest.json").read_text(encoding="utf-8"))
    if not manifest.get("finished"):
        raise SystemExit("corpus is not finished")
    names = [s["file"] for s in manifest["shards"]] + ["manifest.json", "masks.npy", "ids.npy", "uids.csv", "picks.jsonl"]
    for name in names:
        link_or_copy(CORPUS / name, out / name)
    meta = {"title": "knee-raptor-corpus-336", "id": f"{user}/knee-raptor-corpus-336", "licenses": [{"name": "other"}],
            "isPrivate": True, "description": f"Private: Raptor contract {manifest['contract']} corpus built from the competition ZIP (uint8 shards)."}
    (out / "dataset-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    total = sum((out / n).stat().st_size for n in names)
    return {"files": names, "bytes": total}


def publish(out: Path, message: str):
    meta = json.loads((out / "dataset-metadata.json").read_text(encoding="utf-8"))
    # `datasets status` answers 403 for our own private datasets; listing files works and fails cleanly when absent.
    check = kaggle("datasets", "files", meta["id"])
    exists = check.returncode == 0 and "name" in check.stdout
    args = ["datasets", "version", "-p", str(out), "-m", message, "--dir-mode", "zip"] if exists else \
           ["datasets", "create", "-p", str(out), "--dir-mode", "zip"]
    print(("versioning " if exists else "creating ") + meta["id"], flush=True)
    t0 = time.time()
    result = kaggle(*args)
    print(result.stdout[-1500:], result.stderr[-800:], flush=True)
    print(f"{'ok' if result.returncode == 0 else 'FAILED'} in {time.time() - t0:.0f}s", flush=True)
    return result.returncode


def write_kernel(out: Path, user: str, tag: str, train: str, slug: str | None = None, accelerator: str = "gpu"):
    """A private Kaggle script kernel that runs one training job on the attached datasets."""
    slug = slug or kernel_slug(tag)
    args = shlex.split(train)
    parser = argparse.ArgumentParser(add_help=False, allow_abbrev=False)
    parser.add_argument("--amp", choices=["bf16", "fp16", "none"])
    parsed, _ = parser.parse_known_args(args)
    # Do not allow earlier BF16 occurrences to be hidden by a later option.
    amps = [x.split("=", 1)[1] for x in args if x.startswith("--amp=")]
    amps += [args[i + 1] for i, x in enumerate(args[:-1]) if x == "--amp"]
    if "bf16" in amps:
        raise SystemExit("Kaggle GPUs (T4/P100) have no native bf16: use --amp fp16")
    if parsed.amp is None:
        train = f"{train} --amp fp16"
    out.mkdir(parents=True, exist_ok=True)
    (out / "run.py").write_text(KERNEL_TEMPLATE.format(tag=tag, train=train), encoding="utf-8")
    meta = {"id": f"{user}/{slug}", "title": slug, "code_file": "run.py", "language": "python", "kernel_type": "script",
            "is_private": True, "enable_gpu": accelerator == "gpu", "enable_internet": True,
            "dataset_sources": [f"{user}/knee-raptor-tools", f"{user}/knee-raptor-corpus-336"],
            "competition_sources": [], "kernel_sources": []}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return meta


def local_tags():
    return {d.name for d in EXPERIMENTS.iterdir() if (d / "summary.json").exists()} if EXPERIMENTS.exists() else set()


def import_run(run: Path, dest_root: Path):
    """Copy one remote result folder into dest_root/<TAG>; never overwrite an existing run."""
    info = json.loads((run / "run_remote.json").read_text(encoding="utf-8")) if (run / "run_remote.json").exists() else {}
    tag = info.get("tag") or run.name
    dest = dest_root / tag
    if (dest / "summary.json").exists():
        print("exists, kept local copy:", dest); return None
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(run, dest, ignore=shutil.ignore_patterns("dataset-metadata.json"))
    summary = json.loads((dest / "summary.json").read_text(encoding="utf-8"))
    print(f"imported {tag} -> {dest} | weak OOF {summary.get('weak_oof_macro_auc')} | gold {summary.get('gold_once_after_weak_selected_epoch')}"
          f" | {info.get('platform', '?')} {info.get('gpu', '')}")
    return tag


def scratch(name: str) -> Path:
    tmp = ROOT / ".local" / name
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    return tmp


def my_result_datasets():
    refs, page = [], 1
    while page <= 10:
        r = kaggle("datasets", "list", "--mine", "--search", RESULTS_PREFIX, "--csv", "--page", str(page))
        rows = [row for row in csv.DictReader(io.StringIO(r.stdout)) if row.get("ref", "").split("/")[-1].startswith(RESULTS_PREFIX)]
        if not rows:
            break
        refs += [row["ref"] for row in rows]
        page += 1
    return refs


def fetch_results(user: str, tag: str | None, dest_root: Path):
    """Download Colab per-run datasets that are not yet in dest_root."""
    have = {results_slug(t) for t in local_tags()} if dest_root == EXPERIMENTS else set()
    refs = [f"{user}/{results_slug(tag)}"] if tag else [r for r in my_result_datasets() if r.split("/")[-1] not in have]
    tmp, done = scratch("remote-results"), []
    for ref in refs:
        d = tmp / ref.split("/")[-1]
        r = kaggle("datasets", "download", "-d", ref, "-p", str(d), "--unzip", "-q")
        if r.returncode or not any(d.rglob("summary.json")):
            print("not ready or missing:", ref, (r.stderr or r.stdout)[-300:].strip()); continue
        for summary in d.rglob("summary.json"):
            got = import_run(summary.parent, dest_root)
            if got:
                done.append(got)
    shutil.rmtree(tmp, ignore_errors=True)  # checkpoints are ~300 MB each; the imported copy is the one to keep
    print("fetched:", done or "nothing new")
    return done


def fetch_kernel(user: str, tag: str | None, kernel: str | None, dest_root: Path):
    """Pull a Kaggle notebook run's output and import results/<TAG> folders."""
    ref = kernel or f"{user}/{kernel_slug(tag)}"
    status = kaggle("kernels", "status", ref)
    print(status.stdout.strip() or status.stderr.strip())
    tmp = scratch("remote-kernel")
    kaggle("kernels", "output", ref, "-p", str(tmp), check=True)
    done, log = [], next(tmp.glob("*.log"), None)
    for summary in tmp.rglob("results/*/summary.json"):
        if tag and summary.parent.name != tag:
            continue
        got = import_run(summary.parent, dest_root)
        if got:
            done.append(got)
            if log:
                shutil.copy2(log, dest_root / got / "kernel.log")
    if done:
        shutil.rmtree(tmp, ignore_errors=True)
    else:
        print("no new results; notebook log kept at", log)
    return done


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("action", choices=["build", "publish", "kernel", "fetch-kernel", "fetch-results"])
    ap.add_argument("--tag", default=None, help="run tag (kernel, fetch-kernel; fetch-results: only this run)")
    ap.add_argument("--train", default=None, help="kernel: raptor_train.py arguments")
    ap.add_argument("--slug", default=None, help="kernel/fetch-kernel: notebook slug (default knee-raptor-run-<tag>)")
    ap.add_argument("--dir", default=None, help="kernel: package dir (default kaggle/packages/KNEE_RAPTOR_RUN_<TAG>)")
    ap.add_argument("--push", action="store_true", help="kernel: push the private notebook to run now")
    ap.add_argument("--dest", default=None, help="fetch-*: import root (default artifacts/experiments)")
    ap.add_argument("--kind", default="tools", choices=["tools", "corpus"])
    ap.add_argument("--message", default=time.strftime("update %Y-%m-%d %H:%M"))
    a = ap.parse_args()
    user = username()
    dest = Path(a.dest).resolve() if a.dest else EXPERIMENTS
    if a.action == "fetch-results":
        fetch_results(user, a.tag, dest); return
    if a.action == "fetch-kernel":
        if not (a.tag or a.slug):
            raise SystemExit("--tag or --slug required")
        fetch_kernel(user, a.tag, f"{user}/{a.slug}" if a.slug else None, dest); return
    if a.action == "kernel":
        if not (a.tag and a.train):
            raise SystemExit("--tag and --train required")
        out = Path(a.dir).resolve() if a.dir else PACKAGES / f"KNEE_RAPTOR_RUN_{a.tag}"
        meta = write_kernel(out, user, a.tag, a.train, a.slug)
        print("wrote", out, "->", meta["id"])
        if a.push:
            r = kaggle("kernels", "push", "-p", str(out), check=True)
            print(r.stdout.strip().splitlines()[-1] if r.stdout.strip() else r.stderr.strip())
        return
    out = PACKAGES / ("KNEE_RAPTOR_TOOLS" if a.kind == "tools" else "KNEE_RAPTOR_CORPUS_336")
    if a.action == "build":
        info = build_tools(out, user) if a.kind == "tools" else build_corpus(out, user)
        print(json.dumps({k: (v if not isinstance(v, list) else len(v)) for k, v in info.items()}), "->", out)
    else:
        sys.exit(publish(out, a.message))


if __name__ == "__main__":
    main()
