def launcher(data):
    data = patch(data, 'seed42 launcher v2.0.0', 'seed43 launcher v3.0.0')
    return patch(data, OLD_STAGE, STAGE_NAME, 2)


def transfer(data):
    for old, new, count in [
        ('L2 transfer v2.0.1. Changelog: tar/pin confined to a fresh dedicated upload directory.',
         'L2 seed43 transfer v3.0.0. Changelog: isolated seed43 upload, deployment and Pull paths.', 1),
        (r'hb156-l2\H-B-156-L2', r'hb156-l2-s43\H-B-156-L2-S43', 1),
        ('hb156-convnext-l2-s42-v1', DEPLOY, 9),
        (OLD_STAGE, STAGE_NAME, 2),
        ('hb156-l2-upload-v1', 'hb156-l2-s43-upload-v1', 3),
    ]:
        data = patch(data, old, new, count)
    return data


def omitted(rel):
    return rel.startswith('evidence/') or rel in {'BUILD.md','LAUNCH.md',OLD_STAGE+'/cpu-validation.json'}


def parent_inventory():
    need(sha(PARENT/'INVENTORY.json') == PARENT_PIN, 'parent inventory identity drift')
    inventory = read(PARENT/'INVENTORY.json')
    for entry in inventory['files']:
        need(sha(PARENT/entry['path']) == entry['sha256'], 'parent inventory drift: '+entry['path'])
    need(sha(ROOT/'tools/hb156_transfer_v2.ps1') == TRANSFER_PIN, 'parent transfer identity drift')
    return inventory


def safe_build_target():
    need(not any((STAGE/n).exists() for n in ('S43','smoke-attempt','independent-review.json','budget.json','export')),
         'candidate has execution state; rebuild refused')


def expected_manifest(before):
    p = copy.deepcopy(before)
    p.update(schema='hb156-convnext-l2-s43/v1',version=VERSION,run_dirs={'local':STAGE_NAME+'/S43'})
    p['recipe']['seed_local'] = 43
    for rel in ('run.sh','tools/hb156_vast_v1.py','tools/hb156_package_v3.py'):
        p['source_bindings'][rel] = sha(PACKAGE/rel)
    p.pop('content_sha256'); p['content_sha256'] = json_hash(p)
    return p


def expected_kill():
    p = read(PARENT/OLD_STAGE/'kill-test.json')
    p.update(version=VERSION,candidate=DEPLOY,seed=43,protocol_sha256=sha(STAGE/'manifest.json'))
    return p


def build():
    safe_build_target()
    inventory = parent_inventory()
    for entry in inventory['files']:
        rel = entry['path']
        if omitted(rel):
            continue
        dest = PACKAGE/rel.replace(OLD_STAGE,STAGE_NAME)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(PARENT/rel, dest)
    for rel, transform, project in [('tools/hb156_vast_v1.py',runtime,'tools/hb156_vast_v3.py'),
                                    ('run.sh',launcher,'tools/hb156_run_v3.sh')]:
        payload = transform((PARENT/rel).read_bytes())
        (PACKAGE/rel).write_bytes(payload)
        (ROOT/project).write_bytes(payload)
    (ROOT/'tools/hb156_transfer_v3.ps1').write_bytes(transfer((ROOT/'tools/hb156_transfer_v2.ps1').read_bytes()))
    shutil.copyfile(ROOT/'tools/hb156_package_v3.py', PACKAGE/'tools/hb156_package_v3.py')
    write_json(STAGE/'manifest.json',expected_manifest(read(PARENT/OLD_STAGE/'manifest.json')))
    write_json(STAGE/'kill-test.json',expected_kill())
    proof()
    print(json.dumps(dict(status='PREPARED',version=VERSION,package=str(PACKAGE),seed=43)))


def proof():
    inventory = parent_inventory()
    before = read(PARENT/OLD_STAGE/'manifest.json')
    after = read(STAGE/'manifest.json')
    need(after == expected_manifest(before), 'non-allowlisted manifest delta')
    need(after['label_sha256'] == LABEL_SHA, 'L2 identity drift')
    need(read(STAGE/'kill-test.json') == expected_kill(), 'kill-test metadata drift')
    need((PACKAGE/'tools/hb156_package_v3.py').read_bytes() == (ROOT/'tools/hb156_package_v3.py').read_bytes(), 'builder binding drift')
    transforms = {'run.sh':launcher,'tools/hb156_vast_v1.py':runtime}
    changed, same, skipped, lines = [], [], [], []
    retained = set()
    for entry in inventory['files']:
        rel = entry['path']; destrel = rel.replace(OLD_STAGE,STAGE_NAME)
        if omitted(rel):
            skipped.append(rel); continue
        retained.add(destrel)
        old, new = (PARENT/rel).read_bytes(), (PACKAGE/destrel).read_bytes()
        if rel in transforms:
            need(new == transforms[rel](old), 'non-allowlisted code delta: '+rel)
        elif rel not in (OLD_STAGE+'/manifest.json',OLD_STAGE+'/kill-test.json'):
            need(old == new, 'non-allowlisted byte delta: '+rel)
        record = dict(path=rel,candidate_path=destrel,parent_sha256=entry['sha256'],candidate_sha256=sha(PACKAGE/destrel))
        (same if old == new else changed).append(record)
        if rel in transforms or rel.endswith('/kill-test.json'):
            lines.extend(difflib.unified_diff(old.decode().splitlines(True),new.decode().splitlines(True),fromfile='parent/'+rel,tofile='candidate/'+destrel))
    # Never expose label rows. Full JSON equality above proves every manifest field;
    # this redacted structural delta includes only the seed and metadata fields.
    delta = {k:dict(before=before.get(k),after=after.get(k)) for k in sorted(set(before)|set(after)) if before.get(k)!=after.get(k)}
    need(set(delta)=={'schema','version','run_dirs','recipe','source_bindings','content_sha256'}, 'unexpected manifest fields')
    need(dict(before['recipe'],seed_local=43)==after['recipe'], 'recipe is not seed-only')
    for name in ('tools/hb156_vast_v3.py','tools/hb156_run_v3.sh'):
        embedded = 'tools/hb156_vast_v1.py' if name.endswith('.py') else 'run.sh'
        need((ROOT/name).read_bytes()==(PACKAGE/embedded).read_bytes(), 'project source drift: '+name)
    old = (ROOT/'tools/hb156_transfer_v2.ps1').read_bytes()
    new = (ROOT/'tools/hb156_transfer_v3.ps1').read_bytes()
    need(new==transfer(old),'transfer non-allowlisted delta')
    lines.extend(difflib.unified_diff(old.decode().splitlines(True),new.decode().splitlines(True),fromfile='tools/hb156_transfer_v2.ps1',tofile='tools/hb156_transfer_v3.ps1'))
    lines.extend(difflib.unified_diff([], (ROOT/'tools/hb156_package_v3.py').read_text(encoding='utf-8').splitlines(True),fromfile='/dev/null',tofile='tools/hb156_package_v3.py'))
    actual = {p.relative_to(PACKAGE).as_posix() for p in PACKAGE.rglob('*') if p.is_file() and '__pycache__' not in p.parts}
    extras = actual-retained-ADDED
    allowed_evidence = {'BUILD.md','LAUNCH.md','INVENTORY.json','SHA256SUMS',STAGE_NAME+'/cpu-validation.json',STAGE_NAME+'/cpu-checkpoint.pt'}
    need(all(p in allowed_evidence or p.startswith('evidence/') for p in extras), 'unexpected candidate file')
    need(not any(p.startswith('evidence/') and p.endswith(('.pt','.npy','.npz','.csv','.tar')) for p in extras), 'data in evidence')
    report = dict(status='PASS',version=VERSION,parent_inventory_sha256=PARENT_PIN,parent_transfer_sha256=TRANSFER_PIN,
        parent_files_verified=len(inventory['files']),unchanged=same,changed=changed,omitted=skipped,
        additions=sorted(ADDED),regenerated_evidence=sorted(extras),manifest_delta=delta,
        science_delta={'recipe.seed_local':[42,43]},trainer_byte_identical=True,
        labels_byte_identical=True,label_sha256=LABEL_SHA,launch_import_pool_timing_unchanged=True,
        redaction='Manifest label rows omitted; complete in-memory equality checked against seed-only expected parent.')
    write_json(WORK/'mechanical-diff.json',report)
    write(WORK/'full-code.diff',''.join(lines))
    return report


def archive():
    safe_build_target(); proof()
    excluded = {'cpu-checkpoint.pt','INVENTORY.json','SHA256SUMS'}
    paths = sorted(p for p in PACKAGE.rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.name not in excluded)
    need(not any('cache' in p.relative_to(PACKAGE).parts for p in paths), 'corpus upload forbidden')
    files = [dict(path=p.relative_to(PACKAGE).as_posix(),bytes=p.stat().st_size,sha256=sha(p)) for p in paths]
    write_json(PACKAGE/'INVENTORY.json',dict(version=VERSION,files=files))
    write(PACKAGE/'SHA256SUMS',''.join(f"{p['sha256']}  {p['path']}\n" for p in files))
    target = WORK/(DEPLOY+'.tar')
    with tarfile.open(target,'w') as tar:
        for path in paths+[PACKAGE/'INVENTORY.json',PACKAGE/'SHA256SUMS']:
            tar.add(path,arcname=DEPLOY+'/'+path.relative_to(PACKAGE).as_posix(),recursive=False)
    write(target.with_suffix('.tar.sha256'),sha(target)+'  '+target.name+'\n')
    print(json.dumps(dict(status='ARCHIVED',files=len(files),bytes=target.stat().st_size,sha256=sha(target))))


def validate():
    report = proof()
    inventory = read(PACKAGE/'INVENTORY.json')
    excluded = {'cpu-checkpoint.pt','INVENTORY.json','SHA256SUMS'}
    actual = {p.relative_to(PACKAGE).as_posix() for p in PACKAGE.rglob('*')
              if p.is_file() and '__pycache__' not in p.parts and p.name not in excluded}
    names = [e['path'] for e in inventory['files']]
    need(len(names)==len(set(names)) and set(names)==actual, 'candidate inventory roster drift')
    checksums = ''.join(f"{e['sha256']}  {e['path']}\n" for e in inventory['files'])
    need((PACKAGE/'SHA256SUMS').read_text(encoding='utf-8')==checksums, 'SHA256SUMS drift')
    for entry in inventory['files']:
        need(sha(PACKAGE/entry['path'])==entry['sha256'], 'candidate inventory drift: '+entry['path'])
    target = WORK/(DEPLOY+'.tar')
    need(sha(target)==target.with_suffix('.tar.sha256').read_text().split()[0], 'archive pin drift')
    expected = {e['path']:e['sha256'] for e in inventory['files']}
    expected.update({name:sha(PACKAGE/name) for name in ('INVENTORY.json','SHA256SUMS')})
    with tarfile.open(target) as tar:
        members=tar.getmembers()
        need(len(members)==len(expected) and {m.name for m in members}=={DEPLOY+'/'+n for n in expected}, 'tar roster drift')
        for member in members:
            need(member.isfile(), 'tar non-file')
            with tar.extractfile(member) as stream:
                need(hashlib.file_digest(stream,'sha256').hexdigest()==expected[member.name.removeprefix(DEPLOY+'/')], 'tar byte drift')
    print(json.dumps(dict(status='PASS_ARCHIVE',parent_files=report['parent_files_verified'],unchanged=len(report['unchanged']),changed=len(report['changed']),tar_sha256=sha(target))))


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
