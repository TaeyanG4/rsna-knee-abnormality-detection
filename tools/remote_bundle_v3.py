def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def protocol_files(root, protocol_dir):
    """manifest + keys file + every source binding + every fold file the protocol references, with their expected sha256 (None = unbound)."""
    p = read(Path(root) / protocol_dir / 'manifest.json')
    expected = {protocol_dir + '/manifest.json': None, **p['source_bindings']}
    for v in p['folds'].values():
        for key in ('ordered_ids', 'groups'):
            expected[v[key]['path']] = v[key]['sha256']
    return expected


def bundle_files(root=ROOT):
    expected = {f: None for f in CODE_FILES}
    for job in JOBS.values():
        for f, h in protocol_files(root, job['protocol']).items():
            if expected.get(f) not in (None, h):
                raise ValueError('conflicting hashes for ' + f)
            expected[f] = h if h is not None else expected.get(f)
    bad = [f for f in expected if f.startswith(FORBIDDEN_PREFIXES) or Path(f).name == 'train.csv' or Path(f).is_absolute() or '..' in Path(f).parts]
    if bad:
        raise ValueError('refusing to ship: ' + ', '.join(bad))
    return dict(sorted(expected.items()))


def build(root=ROOT, package=PACKAGE, user=None):
    root, package = Path(root), Path(package)
    files = bundle_files(root)
    if package.exists():
        shutil.rmtree(package)
    for rel, expected in files.items():
        src, dst = root / rel, package / rel
        if expected is not None and sha256(src) != expected:
            raise ValueError(f'{rel} differs from the protocol binding')
        dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(src, dst)
        if sha256(dst) != sha256(src):
            raise ValueError('copy changed bytes: ' + rel)
    (package / 'config').mkdir(exist_ok=True)
    (package / 'config' / 'workspace.toml').write_bytes(WORKSPACE_TOML.encode('utf-8'))
    user = user or _username()
    meta = {'title': DATASET, 'id': f'{user}/{DATASET}', 'licenses': [{'name': 'other'}], 'isPrivate': True,
            'description': 'Private: EXP101 arch-generic 5-fold runner, frozen protocol inputs (EXP084 split, EXP099 folds) and Dread labels for '
                           'remote GPU runs (no report text, no Gold).'}
    (package / 'dataset-metadata.json').write_text(json.dumps(meta, indent=1), encoding='utf-8')
    shipped = sorted(p.relative_to(package).as_posix() for p in package.rglob('*') if p.is_file())
    manifest = {'built_at': time.strftime('%Y-%m-%dT%H:%M:%S%z'), 'files': shipped,
                'sha256': {f: sha256(package / f) for f in shipped if f != 'dataset-metadata.json'},
                'protocols': {j: dict(path=v['protocol'], sha256=sha256(package / v['protocol'] / 'manifest.json')) for j, v in JOBS.items()}}
    (package / 'bundle_manifest.json').write_text(json.dumps(manifest, indent=1), encoding='utf-8')
    report = {'package': str(package), 'files': len(shipped) + 1, 'bytes': sum((package / f).stat().st_size for f in shipped), 'protocols': manifest['protocols']}
    print(json.dumps(report, indent=1))
    return report


def _rb():
    from tools import remote_bundle as rb
    return rb


def _username():
    return _rb().username()


def listed_files(ref):
    r = _rb().kaggle('datasets', 'files', ref, '--csv', '--page-size', '200')
    if r.returncode:
        return None
    return [row['name'] for row in csv.DictReader(io.StringIO(r.stdout)) if row.get('name')]


def publish(wait_seconds=1200):
    if not PACKAGE.is_absolute():
        raise ValueError('publish needs an absolute package path (D-B-015)')
    code = _rb().publish(PACKAGE, 'runners v3 ' + time.strftime('%Y-%m-%d %H:%M'))
    if code:
        raise SystemExit(f'publish failed ({code})')
    return wait_listed(wait_seconds)


def wait_listed(wait_seconds=1200):
    """Poll `datasets files` until every bundle file is listed (a new private dataset answers 403 while processing, D-B-015)."""
    meta = read(PACKAGE / 'dataset-metadata.json')
    expected = set(read(PACKAGE / 'bundle_manifest.json')['files']) | {'bundle_manifest.json'}
    expected.discard('dataset-metadata.json')
    t0 = time.time()
    while True:
        names = listed_files(meta['id'])
        missing = sorted(expected - set(names or []))
        print(f"{time.time() - t0:.0f}s: {'not listed yet' if names is None else f'{len(names)} files listed, {len(missing)} missing'}", flush=True)
        if names is not None and not missing:
            print(json.dumps(dict(dataset=meta['id'], files=len(names), status='LISTED')))
            return 0
        if time.time() - t0 > wait_seconds:
            print(json.dumps(dict(dataset=meta['id'], status='NOT_LISTED_IN_TIME', missing=missing[:20])))
            return 3
        time.sleep(30)


def kernel_metadata(user, job):
    spec = JOBS[job]
    return {'id': f"{user}/{spec['slug']}", 'title': spec['slug'], 'code_file': 'run.py', 'language': 'python', 'kernel_type': 'script', 'is_private': True,
            'enable_gpu': True, 'enable_tpu': False, 'enable_internet': True, 'machine_shape': 'NvidiaTeslaT4', 'keywords': ['gpu'],
            'dataset_sources': [f'{user}/{DATASET}', f'{user}/{CORPUS_DATASET}'], 'competition_sources': [], 'kernel_sources': [],
            'docker_image': DOCKER_IMAGE}


def kernel_script(job, user):
    spec = JOBS[job]
    return KERNEL_TEMPLATE.format(job=job, folds=spec['folds'], protocol=spec['protocol'], dataset=f'{user}/{DATASET}', corpus=f'{user}/{CORPUS_DATASET}')


def kernel(job, push):
    user = _username(); spec = JOBS[job]
    out = ROOT / 'kaggle' / 'packages' / spec['package']; out.mkdir(parents=True, exist_ok=True)
    (out / 'run.py').write_text(kernel_script(job, user), encoding='utf-8')
    meta = kernel_metadata(user, job)
    (out / 'kernel-metadata.json').write_text(json.dumps(meta, indent=2), encoding='utf-8')
    print(json.dumps(meta, indent=1))
    if push:
        r = _rb().kaggle('kernels', 'push', '-p', str(out.resolve()), '--accelerator', 'NvidiaTeslaT4', '--timeout', '43200')
        print(r.stdout[-1500:], r.stderr[-800:], flush=True)
        if r.returncode:
            raise SystemExit(f'push failed ({r.returncode})')
        st = _rb().kaggle('kernels', 'status', meta['id'])
        print((st.stdout or st.stderr).strip()[-400:])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='command', required=True)
    sub.add_parser('build')
    s = sub.add_parser('publish'); s.add_argument('--wait', type=int, default=1200)
    s = sub.add_parser('wait'); s.add_argument('--wait', type=int, default=1200)
    k = sub.add_parser('kernel'); k.add_argument('--job', choices=list(JOBS), required=True); k.add_argument('--push', action='store_true')
    a = ap.parse_args()
    for stream in (sys.stdout, sys.stderr):  # Kaggle CLI progress bars contain characters the cp949 console cannot encode
        stream.reconfigure(encoding='utf-8', errors='replace')
    if a.command == 'build':
        build()
    elif a.command == 'publish':
        sys.exit(publish(a.wait))
    elif a.command == 'wait':
        sys.exit(wait_listed(a.wait))
    else:
        kernel(a.job, a.push)


if __name__ == '__main__':
    main()
