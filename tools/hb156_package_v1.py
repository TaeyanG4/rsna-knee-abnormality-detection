from pathlib import Path
import copy
import difflib
import hashlib
import json
import shutil
import tarfile
from tools.hb151_vast44_package_v1 import runtime as seed44_runtime

ROOT = Path(__file__).resolve().parents[1]
PARENT = ROOT/'.local/scratch/astra-b5/H-B-151-seed43/package'
WORK = ROOT/'.local/scratch/slot-b/H-B-156'
PACKAGE = WORK/'package'
STAGE = PACKAGE/'stage-convnext-s42-v1'
ARCH = 'convnext_small.fb_in22k_ft_in1k_384'
URL = 'https://dl.fbaipublicfiles.com/convnext/convnext_small_22k_1k_384.pth'


def sha(path):
    with Path(path).open('rb') as f:
        return hashlib.file_digest(f,'sha256').hexdigest()


def write(path, text):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(text,encoding='utf-8',newline='\n')


def write_json(path, value):
    write(path,json.dumps(value,indent=2,ensure_ascii=False)+'\n')


def names(text):
    return (text.replace('hb151_vast43_v1','hb156_vast_v1')
        .replace('stage-seed43-v1','stage-convnext-s42-v1')
        .replace('hb151-seed43-v1','hb156-convnext-s42-v1').replace('S43','S42'))


def trainer(source):
    result=source.replace('hb151_build_v3','hb156_vast_v1')
    marker='\ndef make_optimization('
    injection='''
# H-B-156 v1.0.0: constructor-only backbone delta; unchanged MIL head.
from functools import partial
from hb156_model_v1 import ARCH, build_model as _candidate_model
build_model = partial(_candidate_model, backbone=ARCH)

'''
    assert result.count(marker)==1
    result=result.replace(marker,injection+marker)
    result=result.replace('from tools.exp112_full_swa import recompute_bn, state_dict_sha256',
        'from tools.exp112_full_swa import state_dict_sha256\n    from hb156_model_v1 import recompute_bn')
    return result


def guard(source, init_hash):
    result=seed44_runtime(source)
    result=result.replace('hb151_vast44_v1','hb156_vast_v1').replace('hb151_vast44_admission_v1','hb156_admission_v1')
    result=result.replace('stage-seed44-v1','stage-convnext-s42-v1').replace('S44','S42')
    import re
    result=re.sub(r'\b44\b','42',result).replace('seed44','seed42')
    result=result.replace("weights/coatnet384-imagenet.pt","weights/convnext-small384-imagenet.pt")
    start=result.index('def verify_trainer():')
    end=result.index('\n\ndef load_registration',start)
    result=result[:start]+'''def verify_trainer():
    from tools.hb156_package_v1 import trainer
    original=(ROOT/'training/src/hb151_v3.py').read_text(encoding='utf-8')
    need((ROOT/'training/src/hb156_vast_v1.py').read_text(encoding='utf-8') == trainer(original),
         'non-allowlisted trainer change')
'''+result[end:]
    result=result.replace('dict(base[\'recipe\'],seed_local=42)',f"dict(base['recipe'],seed_local=42,arch={ARCH!r})")
    result=result.replace("'budgets','init_sha256',","'budgets',")
    result=result.replace("need(p['exposure']=='EXPOSED'",f"need(p['init_sha256']=={init_hash!r},'registered ConvNeXt init drift')\n    need(p['exposure']=='EXPOSED'")
    result=result.replace("dict(base['decision'],seed=42)","dict(base['decision'],seed=42,dead_max=0.946)")
    result=result.replace('from tools.exp112_full_swa import recompute_bn','from hb156_model_v1 import recompute_bn')
    result=result.replace("real_bn_batch2=True, bn_batches=bn['batches']", "real_bn_batch2=True, bn_batches=bn['batches'], bn_modules=bn['bn_modules']")
    result=result.replace('HB151 seed42 Vast guard v1.0.0; generated by hb151_vast44_package_v1.',
        'HB156 ConvNeXt-S seed42 Vast guard v1.0.1; generated by hb156_package_v1.')
    result=result.replace("VERSION='1.0.0'", "VERSION='1.0.1'")
    result += '''

def public_decision(score):
    """Apply the registered standalone boundary; below .950 cannot be GO/alive."""
    need(math.isfinite(score) and 0 <= score <= 1, 'invalid AUC')
    decision = load_registration(PROTOCOL)['decision']
    return ('alive' if score >= decision['alive_min'] else
            'dead' if score <= decision['dead_max'] else 'seed43')
'''
    return result


def build():
    import torch
    import timm
    from timm.models.convnext import checkpoint_filter_fn
    assert timm.__version__=='1.0.19' and ARCH in timm.list_models(pretrained=True)
    WORK.mkdir(parents=True,exist_ok=True); PACKAGE.mkdir(exist_ok=True)
    assert not any((STAGE/n).exists() for n in ('S42','smoke-attempt','independent-review.json'))
    raw=WORK/'convnext_small_22k_1k_384.pth'
    model=timm.create_model(ARCH,pretrained=False,num_classes=0,global_pool='avg')
    weights=checkpoint_filter_fn(torch.load(raw,map_location='cpu',weights_only=True),model)
    weights={k:v for k,v in weights.items() if not k.startswith('head.fc.')}
    model.load_state_dict(weights,strict=True)
    init=PACKAGE/'weights/convnext-small384-imagenet.pt';init.parent.mkdir(parents=True,exist_ok=True)
    torch.save(model.state_dict(),init)
    init_hash=sha(init)
    inv=json.loads((PARENT/'INVENTORY.json').read_text(encoding='utf-8'))
    diffs=[]; unchanged=[]; changes=[]
    skip={'BUILD.md','LAUNCH.md','stage-seed43-v1/cpu-validation.json'}
    for entry in inv['files']:
        rel=entry['path'];src=PARENT/rel
        assert sha(src)==entry['sha256'],'frozen parent drift: '+rel
        if rel in skip or rel.startswith('evidence/'): continue
        dest=PACKAGE/names(rel);dest.parent.mkdir(parents=True,exist_ok=True)
        data=src.read_bytes()
        if rel=='tools/hb151_vast43_v1.py': data=guard(data.decode(),init_hash).encode()
        elif rel=='training/src/hb151_vast43_v1.py': data=trainer((PARENT/'training/src/hb151_v3.py').read_text(encoding='utf-8')).encode()
        elif rel=='run.sh':
            data=names(data.decode()).replace('python -B -m tools.hb156_vast_v1 verify',
                'python -B -m tools.hb156_vast_v1 launch-check\npython -B -m tools.hb156_vast_v1 verify').encode()
        dest.write_bytes(data)
        if data==src.read_bytes(): unchanged.append(rel)
        elif not rel.endswith('manifest.json'):
            changes.append(rel)
            diffs.extend(difflib.unified_diff(src.read_text(encoding='utf-8').splitlines(True),data.decode().splitlines(True),fromfile=rel,tofile=names(rel)))
    helper=(ROOT/'tools/hb151_vast44_admission_v1.py').read_text(encoding='utf-8')
    helper=helper.replace("'hb151' in arg.lower()", "any(tag in arg.lower() for tag in ('hb151','hb156'))")
    helper=helper.replace('HB151 fit/smoke','HB151/HB156 fit/smoke')
    write(ROOT/'tools/hb156_admission_v1.py',helper)
    for rel in ('training/src/hb156_model_v1.py','tools/hb156_admission_v1.py','tools/hb156_package_v1.py','tools/hb151_vast44_package_v1.py'):
        shutil.copyfile(ROOT/rel,PACKAGE/rel)
        diffs.extend(difflib.unified_diff([], (ROOT/rel).read_text(encoding='utf-8').splitlines(True),fromfile='/dev/null',tofile=rel))
    p=json.loads((PARENT/'stage-seed43-v1/manifest.json').read_text(encoding='utf-8'))
    old=copy.deepcopy(p)
    p['schema']='hb156-convnext-s42/v1';p['recipe'].update(seed_local=42,arch=ARCH)
    p['decision'].update(seed=42,dead_max=0.946)
    p['run_dirs']={'local':'stage-convnext-s42-v1/S42'};p['init_sha256']=init_hash
    p['source_bindings']={names(k):sha(PACKAGE/names(k)) for k in p['source_bindings']}
    for rel in ('training/src/hb156_model_v1.py','tools/hb156_admission_v1.py','tools/hb156_package_v1.py','tools/hb151_vast44_package_v1.py'):
        p['source_bindings'][rel]=sha(PACKAGE/rel)
    p.pop('content_sha256');p['content_sha256']=hashlib.sha256(json.dumps(p,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()).hexdigest()
    write_json(STAGE/'manifest.json',p);write_json(STAGE/'decision.json',p['decision'])
    expected=copy.deepcopy(old)
    for key in ('schema','source_bindings','content_sha256','run_dirs','init_sha256'): expected[key]=p[key]
    expected['recipe'].update(seed_local=42,arch=ARCH);expected['decision'].update(seed=42,dead_max=0.946)
    assert p==expected,'non-allowlisted scientific change'
    unchanged=[rel for rel in unchanged if (PARENT/rel).read_bytes()==(PACKAGE/names(rel)).read_bytes()]
    write_json(WORK/'mechanical-diff.json',dict(status='PASS',parent_files_verified=len(inv['files']),
        unchanged_files=unchanged,changed_code=changes,recipe_delta={'arch':ARCH,'seed_local':42},
        decision_delta={'seed':42,'dead_max':0.946},labels_byte_identical=True,
        accommodations=['LayerNorm-only backbone: same full replay with zero BN statistics','seed44 shared lock and admission extended to hb156'],
        serving='constructor only; default CoAtNet delegates unchanged; strict state reload'))
    for key in ('recipe','decision','source_bindings','init_sha256'):
        diffs.extend(difflib.unified_diff(json.dumps(old[key],indent=2).splitlines(True),json.dumps(p[key],indent=2).splitlines(True),fromfile='parent/'+key,tofile='candidate/'+key))
    write(WORK/'full-code.diff',''.join(diffs))
    write_json(PACKAGE/'weights/provenance.json',dict(arch=ARCH,timm='1.0.19',source_url=URL,
        source_sha256=sha(raw),packaged_sha256=init_hash,conversion='timm checkpoint_filter_fn; remove head.fc classifier; strict backbone load',offline=True))
    for rel in ('tools/hb156_vast_v1.py','training/src/hb156_vast_v1.py'):
        shutil.copyfile(PACKAGE/rel,ROOT/rel)
    shutil.copyfile(PACKAGE/'run.sh',ROOT/'tools/hb156_run_v1.sh')
    transfer=names((ROOT/'tools/hb151_vast43_transfer_v1.ps1').read_text(encoding='utf-8'))
    transfer=transfer.replace('.local\\scratch\\astra-b5\\H-B-151-seed43','.local\\scratch\\slot-b\\H-B-156')
    write(ROOT/'tools/hb156_transfer_v1.ps1',transfer)
    print(json.dumps(dict(status='BUILT',arch=ARCH,seed=42,labels_sha256=p['label_sha256'],init_sha256=init_hash)))


def archive():
    paths=sorted(p for p in PACKAGE.rglob('*') if p.is_file() and '__pycache__' not in p.parts
        and p.name not in ('cpu-checkpoint.pt','INVENTORY.json','SHA256SUMS'))
    assert not any((STAGE/n).exists() for n in ('S42','smoke-attempt','independent-review.json'))
    inv=[dict(path=p.relative_to(PACKAGE).as_posix(),bytes=p.stat().st_size,sha256=sha(p)) for p in paths]
    write_json(PACKAGE/'INVENTORY.json',dict(version='1.0.1',files=inv))
    write(PACKAGE/'SHA256SUMS',''.join(f"{p['sha256']}  {p['path']}\n" for p in inv))
    target=WORK/'hb156-convnext-s42-v1.tar'
    with tarfile.open(target,'w') as tar:
        for p in paths+[PACKAGE/'INVENTORY.json',PACKAGE/'SHA256SUMS']:
            tar.add(p,arcname='hb156-convnext-s42-v1/'+p.relative_to(PACKAGE).as_posix(),recursive=False)
    target.with_suffix('.tar.sha256').write_bytes((sha(target)+'  '+target.name+'\n').encode('ascii'))
    print(json.dumps(dict(status='ARCHIVED',files=len(inv),bytes=target.stat().st_size,sha256=sha(target))))


if __name__=='__main__':
    import sys
    archive() if sys.argv[1:]==['archive'] else build()
